async def _run_agent_loop_impl(
    runtime: ChatRuntime,
    req: SendMessageRequest,
    state: ChatSessionState,
    budget: TurnBudgetLedger,
) -> AsyncIterator[str]:
    """Drive the LLM through the configured number of bounded tool turns.

    On exit the following ``state`` fields are populated for the persist step:

    * ``state.full_text``                  — concatenated user-visible text
    * ``state.steps``                      — per-iteration audit records
    * ``state.tool_call_events``           — UI summary of every tool execution
    * ``state.tool_result_blocks``         — last batch fed back to the LLM
    * ``state.artifacts``                  — collected via tool_executor
    * ``state.pending_markdown_saves``     — collected via tool_executor
    * ``state.pending_tool_actions``       — HITAS rows to persist
    * ``state.pending_tool_confirmations`` — frontend confirmation cards
    * ``state.confirmation_requested``     — early-exit signal for persist
    * ``state.trace_events``               — diagnostic stream
    """
    messages: list[dict] = list(runtime.api_messages)
    accumulated_text = ""
    workflow_announced = False
    loop_started_at = time.perf_counter()

    for step_index in range(budget.limits.max_steps):
        budget.start_step(phase=f"step_{step_index}")
        step = AgentStep(index=step_index)
        state.steps.append(step)
        step_started_at = time.perf_counter()

        # Product Run Event v1: open a step (1-based index; title is generic
        # because tool names aren't known until the model emits tool_use blocks).
        if state.run_id:
            yield sse_event(
                _step_started_event(state.run_id, step_index + 1, title=f"第 {step_index + 1} 步")
            )

        # ---------- one LLM turn (events stream out live as the model writes) ----------
        result = _StreamResult()
        try:
            async for ev in _consume_stream(
                runtime,
                state,
                messages,
                step_index=step_index,
                stream_label=f"step_{step_index}",
                result=result,
            ):
                yield ev
        finally:
            # Keep the text visible so far available to the outer interruption
            # boundary even when cancellation lands in the middle of a stream.
            step.model_text = result.text
            state.full_text = _append_text(accumulated_text, result.text)
        text = result.text
        tool_calls = result.tool_calls
        reasoning = result.reasoning
        truncated = result.truncated

        # ---------- truncation auto-continue (any step that ended on a cut-off
        # final answer, i.e. no tools emitted) ----------
        if truncated and not tool_calls and text.strip():
            cont_messages = messages + [
                {"role": "assistant", "content": text.strip()},
                {"role": "user", "content": _CONTINUATION_PROMPT},
            ]
            cont_result = _StreamResult()
            try:
                async for ev in _consume_stream(
                    runtime,
                    state,
                    cont_messages,
                    step_index=step_index,
                    stream_label=f"step_{step_index}_continuation",
                    result=cont_result,
                ):
                    yield ev
            finally:
                step.model_text = text + cont_result.text
                state.full_text = _append_text(accumulated_text, step.model_text)
            text += cont_result.text
            reasoning += cont_result.reasoning
            tool_calls.extend(cont_result.tool_calls)
            if cont_result.truncated:
                yield sse_event({"type": "truncated", "can_continue": True})
                truncated = True
            else:
                truncated = False
        elif truncated:
            # Truncated while still planning tools — no clean continuation path,
            # so surface it to the UI instead of auto-continuing.
            yield sse_event({"type": "truncated", "can_continue": True})

        planned_calls = normalize_planned_tool_calls(tool_calls, step_index=step_index)
        tool_calls = planned_calls.tool_calls
        if planned_calls.changed:
            state.record_trace_event(
                "planned_tool_calls_normalized",
                stage=f"step_{step_index}",
                **planned_calls.metrics(),
            )
            logger.warning(
                "[tool-transcript] normalized planned calls step=%s issues=%s removed_duplicates=%s",
                step_index,
                [issue.code for issue in planned_calls.issues],
                planned_calls.removed_duplicate_count,
            )

        step.model_text = text
        step.reasoning = reasoning
        step.truncated = truncated
        step.tool_calls = list(tool_calls)
        accumulated_text = _append_text(accumulated_text, text)
        state.full_text = accumulated_text

        if not tool_calls:
            step.duration_ms = round((time.perf_counter() - step_started_at) * 1000)
            step.status = "completed"
            _checkpoint_step(state, step)
            if state.run_id:
                yield sse_event(
                    _step_completed_event(
                        state.run_id,
                        step_index + 1,
                        StepCompletedStatus.COMPLETED,
                        step.duration_ms,
                        truncated=truncated,
                    )
                )
            break

        # Reserve the complete normalized batch before executing its first
        # call. This makes the limit atomic: an oversized plan performs none
        # of the newly planned calls.
        budget.reserve_tool_calls(
            len(tool_calls),
            phase=f"step_{step_index}_tools",
        )

        # ---------- mark workflow started once we know tools will run ----------
        # No canned "判断执行方式 / 准备参数" plan steps: the real tool executions
        # streamed below are the visible progress, matching the persisted view.
        if not workflow_announced:
            workflow_announced = True
            state.workflow_started = True

        # ---------- build assistant message + execute tools ----------
        messages.append(_build_assistant_message(text, tool_calls, reasoning))

        tool_result_blocks: list[dict] = []
        execution_plan = plan_tool_execution(
            tool_calls,
            action_policy=runtime.action_policy,
            max_parallel=getattr(runtime, "tool_parallel_max_concurrency", 4),
        )
        state.record_trace_event(
            "tool_execution_planned",
            stage=f"step_{step_index}",
            **execution_plan.to_trace_dict(),
        )
        confirmation_index: int | None = None

        for batch_number, batch in enumerate(execution_plan.batches, start=1):
            batch_started_at = time.perf_counter()
            indexed_calls = [(index, tool_calls[index]) for index in batch.indexes]

            # Emit every running event before a parallel batch begins. Terminal
            # events and model-visible results are still replayed in call order.
            for _, tool_call in indexed_calls:
                if state.run_id:
                    yield sse_event(
                        _tool_progress_event(
                            state.run_id,
                            step_index + 1,
                            title=tool_display_name(str(tool_call.get("name") or "")),
                            status=ToolProgressStatus.RUNNING,
                        )
                    )

            if batch.parallel:
                child_states = [_fork_parallel_tool_state(state) for _ in indexed_calls]
                outcomes = await await_with_turn_deadline(
                    asyncio.gather(
                        *(
                            execute_tool_with_policy(
                                runtime,
                                child_state,
                                tool_call,
                                req=req,
                                step_text=text,
                                step_truncated=truncated,
                                step_index=step_index,
                            )
                            for child_state, (_, tool_call) in zip(child_states, indexed_calls)
                        )
                    ),
                    budget,
                    phase=f"step_{step_index}_tool_batch_{batch_number}",
                    tool_execution_possible=True,
                )
                for child_state in child_states:
                    _merge_parallel_tool_state(state, child_state)
            else:
                _, tool_call = indexed_calls[0]
                outcomes = [
                    await await_with_turn_deadline(
                        execute_tool_with_policy(
                            runtime,
                            state,
                            tool_call,
                            req=req,
                            step_text=text,
                            step_truncated=truncated,
                            step_index=step_index,
                        ),
                        budget,
                        phase=f"step_{step_index}_tool_batch_{batch_number}",
                        tool_execution_possible=True,
                    )
                ]

            state.record_trace_event(
                "tool_execution_batch_completed",
                stage=f"step_{step_index}",
                batch_number=batch_number,
                lane=batch.lane.value,
                tool_count=len(indexed_calls),
                duration_ms=round((time.perf_counter() - batch_started_at) * 1000),
            )

            for (tc_index, tool_call), outcome in zip(indexed_calls, outcomes):
                for ev in outcome.events:
                    yield ev

                # Product Run Event v1: pair each tool with its terminal state.
                if state.run_id:
                    tool_name_v1 = str(tool_call.get("name") or "")
                    tool_title_v1 = tool_display_name(tool_name_v1)
                    if outcome.confirmation_required:
                        pending = (
                            state.pending_tool_confirmations[-1]
                            if state.pending_tool_confirmations
                            else {}
                        )
                        action_text = tool_display_name(
                            str(pending.get("tool_name") or tool_name_v1)
                        )
                        impact_text = (
                            str(pending.get("summary") or "")
                            or "该动作会修改或删除项目内容，需要用户确认才能继续。"
                        )
                        params_snapshot = (
                            pending.get("tool_input")
                            if isinstance(pending.get("tool_input"), dict)
                            else None
                        )
                        yield sse_event(
                            _confirmation_required_event(
                                state.run_id,
                                action=action_text,
                                impact=impact_text,
                                params_snapshot=params_snapshot,
                            )
                        )
                    else:
                        yield sse_event(
                            _tool_progress_event(
                                state.run_id,
                                step_index + 1,
                                title=tool_title_v1,
                                status=_classify_tool_outcome_status(outcome),
                            )
                        )

                # Markdown writes also stream their content as user-visible text.
                if outcome.markdown_inline_text:
                    accumulated_text = _append_text(accumulated_text, outcome.markdown_inline_text)
                    state.full_text = accumulated_text
                    yield sse_event({"type": "text", "content": outcome.markdown_inline_text})
                    if state.run_id:
                        yield sse_event(
                            _text_delta_event(state.run_id, outcome.markdown_inline_text)
                        )

                tool_result_blocks.append(outcome.result_block)
                if outcome.confirmation_required:
                    confirmation_index = tc_index
                    break

            if confirmation_index is not None:
                # Preserve transcript pairing for all calls behind the HITAS
                # barrier without executing them.
                for remaining in tool_calls[confirmation_index + 1 :]:
                    tool_result_blocks.append(_skipped_pending_result_block(remaining))
                break

        messages.append({"role": "user", "content": tool_result_blocks})
        state.tool_result_blocks = tool_result_blocks
        step.tool_results = tool_result_blocks
        step.duration_ms = round((time.perf_counter() - step_started_at) * 1000)
        step_events = [
            event
            for event in state.tool_call_events
            if isinstance(event, dict) and int(event.get("step_index", -1)) == step_index
        ]
        failed_events = [
            event
            for event in step_events
            if tool_event_is_failure(event)
        ]
        if confirmation_index is not None:
            step.status = "waiting_confirmation"
        elif failed_events:
            step.status = "failed"
            step.error = str(
                failed_events[-1].get("error")
                or failed_events[-1].get("summary")
                or "tool execution failed"
            )
            retry_candidates = [
                event
                for event in failed_events
                if str(event.get("status") or "") not in {"blocked", "conflict"}
            ]
            step.retryable = bool(retry_candidates) and all(
                bool(event.get("retryable", False)) for event in retry_candidates
            )
        else:
            step.status = "completed"
        step.retry_count = sum(
            max(0, int(event.get("attempt_count") or 1) - 1)
            for event in step_events
        )
        _checkpoint_step(state, step)

        yield sse_event(build_agent_step_event(step))
        if state.run_id:
            yield sse_event(
                _step_completed_event(
                    state.run_id,
                    step_index + 1,
                    (
                        StepCompletedStatus.FAILED
                        if step.status == "failed"
                        else StepCompletedStatus.COMPLETED
                    ),
                    step.duration_ms,
                    truncated=truncated,
                )
            )

        if state.confirmation_requested:
            break
    else:
        raise budget.step_limit_exceeded(phase="agent_loop")

    state.full_text = accumulated_text
    state.stage_timings["agent_loop_ms"] = round((time.perf_counter() - loop_started_at) * 1000)
    yield sse_event(
        {"type": "timing", "key": "agent_loop_ms", "duration_ms": state.stage_timings["agent_loop_ms"]}
    )


def _budget_exhaustion_notice(exc: TurnBudgetExceeded) -> str:
    if exc.kind is BudgetKind.STEP_LIMIT:
        return (
            f"本轮已达到 {int(exc.limit)} 步执行上限，已停止继续规划。"
            "已有内容和执行记录已保存，你可以发起新一轮继续。"
        )
    if exc.kind is BudgetKind.TOOL_CALL_LIMIT:
        return (
            f"本轮计划的工具调用超过 {int(exc.limit)} 次安全上限，"
            "超出部分未执行。已有内容和执行记录已保存。"
        )
    message = (
        f"本轮已达到 {float(exc.limit):g} 秒最长执行时间，已停止继续运行。"
        "已有内容和执行记录已保存。"
    )
    if exc.tool_execution_possible:
        message += "停止时工具可能已部分执行，请先核对实际结果再重试。"
    return message


async def run_agent_loop(
    runtime: ChatRuntime,
    req: SendMessageRequest,
    state: ChatSessionState,
) -> AsyncIterator[str]:
    """Run one Agent Loop behind a shared, persisted execution budget."""

    limits = normalize_turn_budget_limits(
        max_steps=getattr(runtime, "agent_turn_max_steps", 8),
        max_tool_calls=getattr(runtime, "agent_turn_max_tool_calls", 24),
        max_elapsed_seconds=getattr(runtime, "agent_turn_timeout_seconds", 600.0),
    )
    budget = TurnBudgetLedger(limits)
    state.turn_budget = budget
    loop_started_at = time.perf_counter()
    state.record_trace_event(
        "turn_budget_started",
        stage="agent_loop",
        **budget.snapshot(),
    )

    try:
        async for event in _run_agent_loop_impl(runtime, req, state, budget):
            yield event
    except TurnBudgetExceeded as exc:
        notice = _budget_exhaustion_notice(exc)
        state.budget_exhausted = True
        state.budget_exhaustion = {
            **exc.to_dict(),
            "message": notice,
            "budget": budget.snapshot(),
        }
        state.record_trace_event(
            "turn_budget_exhausted",
            **state.budget_exhaustion,
        )

        if state.steps and state.steps[-1].status == "running":
            step = state.steps[-1]
            step.status = "failed"
            step.error = str(exc)[:500]
            step.retryable = False
            _checkpoint_step(state, step)
            yield sse_event(build_agent_step_event(step))
            if state.run_id:
                yield sse_event(
                    _step_completed_event(
                        state.run_id,
                        step.index + 1,
                        StepCompletedStatus.FAILED,
                        step.duration_ms,
                        truncated=step.truncated,
                    )
                )

        state.full_text = _append_text(state.full_text, notice)
        state.stage_timings["agent_loop_ms"] = round(
            (time.perf_counter() - loop_started_at) * 1000
        )
        yield sse_event({"type": "text", "content": notice})
        if state.run_id:
            yield sse_event(_text_delta_event(state.run_id, notice))
            yield sse_event(
                _run_failed_event(
                    state.run_id,
                    ErrorCode.TURN_BUDGET_EXCEEDED,
                    notice,
                    retryable=False,
                    fallback_content=state.full_text,
                )
            )
        yield sse_event(
            {
                "type": "timing",
                "key": "agent_loop_ms",
                "duration_ms": state.stage_timings["agent_loop_ms"],
            }
        )
