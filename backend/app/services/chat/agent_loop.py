@dataclass
class _StreamResult:
    """Aggregates produced while draining one LLM stream.

    Events are *yielded* live by ``_consume_stream``; these fields hold the
    end-of-turn rollup the caller needs (final text, planned tool calls,
    extended-thinking reasoning, and whether the output was truncated).
    """

    text: str = ""
    tool_calls: list[dict] = field(default_factory=list)
    reasoning: str = ""
    truncated: bool = False


async def _iter_model_stream_with_safe_retry(
    runtime: ChatRuntime,
    state: ChatSessionState,
    request_messages: list[dict],
    request_system: str,
    *,
    stream_label: str,
) -> AsyncIterator[str | dict]:
    """Yield one model stream with a fail-closed replay boundary.

    Heartbeats are generated by Aria and do not commit the provider response.
    Any string yielded by the provider — including reasoning/tool markers and
    even an empty provider event — does commit it. A later failure is surfaced
    instead of replayed, so already rendered text or planned tool calls can
    never be duplicated by automatic recovery.
    """

    max_attempts = normalize_max_attempts(getattr(runtime, "model_turn_max_attempts", 2))
    base_delay_ms = int(getattr(runtime, "model_turn_retry_base_delay_ms", 500))
    max_delay_ms = int(getattr(runtime, "model_turn_retry_max_delay_ms", 5_000))
    response_committed = False

    for attempt in range(1, max_attempts + 1):
        try:
            source = runtime.llm.stream_response(
                request_messages,
                system=request_system,
                model=runtime.selected_model,
                tools=runtime.tools,
                max_tokens=runtime.max_tokens,
                temperature=runtime.temperature,
            )
            stream = iter_with_heartbeat(
                source,
                stage="thinking",
                # Same text as the initial frontend state to avoid flicker.
                message="Aria 正在思考...",
            )
            budget = state.turn_budget
            if isinstance(budget, TurnBudgetLedger):
                stream = iter_with_turn_deadline(
                    stream,
                    budget,
                    phase=stream_label,
                )
            async for item in stream:
                if not isinstance(item, dict):
                    response_committed = True
                yield item
            return
        except TurnBudgetExceeded:
            # A shared turn deadline is terminal. Replaying the model stream
            # would violate the same deadline and could duplicate committed
            # text/tool plans.
            raise
        except Exception as exc:
            decision = decide_turn_retry(
                exc,
                attempt=attempt,
                max_attempts=max_attempts,
                response_committed=response_committed,
                base_delay_ms=base_delay_ms,
                max_delay_ms=max_delay_ms,
            )
            trace_payload = decision.to_trace_dict()
            if not decision.retryable:
                event_type = (
                    "model_turn_retry_suppressed"
                    if decision.response_committed
                    else "model_turn_retry_exhausted"
                    if decision.reason == "attempts_exhausted"
                    else "model_turn_retry_not_allowed"
                )
                state.record_trace_event(event_type, stage=stream_label, **trace_payload)
                logger.warning(
                    "[model-turn] retry stopped stage=%s attempt=%s/%s "
                    "category=%s reason=%s committed=%s error_type=%s",
                    stream_label,
                    attempt,
                    max_attempts,
                    decision.category.value,
                    decision.reason,
                    decision.response_committed,
                    type(exc).__name__,
                )
                raise

            state.record_trace_event(
                "model_turn_retry_scheduled",
                stage=stream_label,
                next_attempt=attempt + 1,
                **trace_payload,
            )
            state.stage_timings["model_retry_count"] = int(
                state.stage_timings.get("model_retry_count", 0) or 0
            ) + 1
            state.stage_timings["model_retry_wait_ms"] = int(
                state.stage_timings.get("model_retry_wait_ms", 0) or 0
            ) + decision.delay_ms
            logger.warning(
                "[model-turn] safe retry stage=%s attempt=%s/%s delay_ms=%s category=%s reason=%s error_type=%s",
                stream_label,
                attempt,
                max_attempts,
                decision.delay_ms,
                decision.category.value,
                decision.reason,
                type(exc).__name__,
            )
            yield {
                "type": "status",
                "stage": "model_retry",
                "message": (
                    "模型服务暂时不可用，正在安全重试"
                    f"（{attempt}/{max_attempts - 1}）..."
                ),
                "attempt": attempt,
                "max_retries": max_attempts - 1,
                "delay_ms": decision.delay_ms,
            }
            retry_wait = asyncio.sleep(decision.delay_ms / 1_000)
            if isinstance(state.turn_budget, TurnBudgetLedger):
                await await_with_turn_deadline(
                    retry_wait,
                    state.turn_budget,
                    phase=f"{stream_label}_retry_wait",
                )
            else:
                await retry_wait


async def _consume_stream(
    runtime: ChatRuntime,
    state: ChatSessionState,
    messages: list[dict],
    *,
    step_index: int,
    stream_label: str,
    result: _StreamResult,
) -> AsyncIterator[str]:
    """Drain a single ``stream_response`` call, yielding SSE frames as they arrive.

    Text deltas, heartbeats and status frames are yielded the moment the model
    produces them, so the frontend renders the reply progressively instead of in
    one burst at end-of-turn. User-visible text, planned tool calls, reasoning
    and the truncation flag are accumulated into ``result`` for the caller.
    """
    started_at = time.perf_counter()
    transcript = normalize_tool_transcript(messages)
    request_messages = transcript.messages
    request_system = runtime.system
    if transcript.changed:
        metrics = transcript.metrics()
        state.record_trace_event(
            "tool_transcript_normalized",
            stage=stream_label,
            **metrics,
        )
        logger.warning(
            "[tool-transcript] normalized stage=%s issues=%s synthetic=%s orphans=%s",
            stream_label,
            metrics["issue_codes"],
            metrics["synthetic_result_count"],
            metrics["removed_orphan_count"],
        )

    context_window_tokens = int(getattr(runtime, "context_window_tokens", 0) or 0)
    if context_window_tokens > 0:
        budgeted = apply_context_budget(
            system=request_system,
            messages=request_messages,
            tools=runtime.tools,
            context_window_tokens=context_window_tokens,
            max_output_tokens=runtime.max_tokens,
            safety_margin_percent=int(
                getattr(runtime, "context_safety_margin_percent", 8) or 8
            ),
            history_summary_tokens=int(
                getattr(runtime, "context_history_summary_tokens", 1_024) or 1_024
            ),
        )
        request_system = budgeted.system
        request_messages = budgeted.messages
        budget_metrics = budgeted.report.to_dict()
        state.record_trace_event(
            "turn_context_budget",
            stage=stream_label,
            **budget_metrics,
        )
        if budgeted.report.compacted:
            logger.info(
                "[context-budget] compacted stage=%s before=%s after=%s messages=%s->%s tool_batches=%s->%s",
                stream_label,
                budgeted.report.estimated_total_before,
                budgeted.report.estimated_total_after,
                budgeted.report.history_messages_before,
                budgeted.report.history_messages_after,
                budgeted.report.tool_batches_before,
                budgeted.report.tool_batches_after,
            )

        # Compaction must retain the same call/result invariants as the input.
        # Normalize again as a fail-closed guard and trace any unexpected repair.
        post_budget_transcript = normalize_tool_transcript(request_messages)
        request_messages = post_budget_transcript.messages
        if post_budget_transcript.changed:
            state.record_trace_event(
                "post_budget_tool_transcript_normalized",
                stage=stream_label,
                **post_budget_transcript.metrics(),
            )
            logger.error(
                "[context-budget] repaired tool transcript after compaction stage=%s issues=%s",
                stream_label,
                [issue.code for issue in post_budget_transcript.issues],
            )

    # The manifest is bound to the exact initial provider request after both
    # transcript normalization and budgeting. Later steps intentionally append
    # tool call/results and receive their own turn_context_budget trace.
    context_manifest = getattr(runtime, "context_manifest", None)
    if context_manifest and step_index == 0 and stream_label == "step_0":
        context_valid, context_reason = validate_context_assembly_request(
            context_manifest,
            system=request_system,
            messages=request_messages,
            tools=runtime.tools,
        )
        if not context_valid:
            state.record_trace_event(
                "context_assembly_request_rejected",
                stage="before_model_request",
                reason=context_reason,
            )
            raise RuntimeError(f"context assembly request rejected: {context_reason}")

    async for item in _iter_model_stream_with_safe_retry(
        runtime,
        state,
        request_messages,
        request_system,
        stream_label=stream_label,
    ):
        if isinstance(item, dict):
            yield sse_event(item)
            continue

        chunk: str = item
        if not state.first_model_event_recorded:
            state.first_model_event_recorded = True
            state.stage_timings["model_first_event_ms"] = round((time.perf_counter() - started_at) * 1000)
            yield sse_event(
                {
                    "type": "timing",
                    "key": "model_first_event_ms",
                    "duration_ms": state.stage_timings["model_first_event_ms"],
                }
            )

        chunk, was_truncated = strip_truncation_marker(chunk)
        if was_truncated:
            result.truncated = True
            yield sse_event(
                {
                    "type": "status",
                    "stage": "continuing",
                    "message": "模型输出较长，已触发长度上限，正在尝试继续生成...",
                }
            )
            if not chunk:
                continue

        stripped = chunk.strip()

        # Internal "[TOOL_START:name]" progress marker
        if stripped.startswith("[TOOL_START:") and stripped.endswith("]"):
            tool_name = stripped[12:-1]
            evaluation = evaluate_tool_policy(runtime.action_policy, tool_name, {})
            if not evaluation.may_plan:
                state.record_trace_event(
                    "tool_marker_suppressed",
                    stage=stream_label,
                    tool_name=tool_name,
                    reason=evaluation.reason,
                    required_policy=evaluation.required_policy.value,
                    current_policy=str(getattr(runtime.action_policy, "value", runtime.action_policy)),
                )
                continue
            progress = _tool_start_progress_payload(tool_name)
            if progress:
                yield sse_event({"type": "tool_executing", "tool_name": tool_name, **progress})
            # v1 tool_progress(running) is emitted around the real tool
            # execution below (so it fires exactly once per tool call,
            # regardless of whether the model emits a [TOOL_START] marker).
            continue

        chunk = _strip_internal_tool_markers(chunk)
        if not chunk:
            continue
        stripped = chunk.strip()

        # Mixed-text tool_use JSON blocks
        mixed, cleaned = extract_tool_use_json_blocks(chunk)
        if mixed:
            for block in mixed:
                if _accept_tool_block(runtime, state, block, stream_label, source="text"):
                    result.tool_calls.append(block)
                    yield sse_event(
                        {
                            "type": "status",
                            "stage": "tool_planned",
                            "message": f"模型已规划调用工具：{block.get('name')}",
                        }
                    )
            if cleaned:
                result.text += cleaned
                yield sse_event({"type": "text", "content": cleaned})
                if state.run_id:
                    yield sse_event(_text_delta_event(state.run_id, cleaned))
            continue

        # Pure JSON tool_use / reasoning_content envelope
        if stripped.startswith("{") and stripped.endswith("}") and '"type"' in stripped:
            try:
                block = json.loads(stripped)
            except json.JSONDecodeError:
                block = None
            if isinstance(block, dict):
                if block.get("type") == "tool_use":
                    if _accept_tool_block(runtime, state, block, stream_label, source="json"):
                        result.tool_calls.append(block)
                        yield sse_event(
                            {
                                "type": "status",
                                "stage": "tool_planned",
                                "message": f"模型已规划调用工具：{block.get('name')}",
                            }
                        )
                    continue
                if block.get("type") == "reasoning_content":
                    result.reasoning += str(block.get("content") or "")
                    continue

        result.text += chunk
        yield sse_event({"type": "text", "content": chunk})
        if state.run_id:
            yield sse_event(_text_delta_event(state.run_id, chunk))


def _classify_tool_outcome_status(outcome: Any) -> str:
    """Map a tool ``ToolOutcome`` to a Product Run Event v1 tool_progress status.

    Reads the JSON-encoded ``content`` of the ``tool_result`` block fed back to
    the LLM. Any explicit error / success=False / status="error|failed" signal
    classifies the call as ``failed``; everything else (incl. unparseable
    payloads, since the tool clearly ran without raising) is ``completed``.
    """
    content_str = ""
    result_block = getattr(outcome, "result_block", None)
    if isinstance(result_block, dict):
        content_str = str(result_block.get("content") or "")
    try:
        payload = json.loads(content_str) if content_str else {}
    except (json.JSONDecodeError, TypeError):
        payload = {}
    if isinstance(payload, dict):
        if payload.get("error"):
            return ToolProgressStatus.FAILED
        if payload.get("success") is False or payload.get("ok") is False:
            return ToolProgressStatus.FAILED
        status_text = str(payload.get("status") or "").lower()
        if status_text in {"error", "failed"}:
            return ToolProgressStatus.FAILED
    return ToolProgressStatus.COMPLETED


def _accept_tool_block(
    runtime: ChatRuntime,
    state: ChatSessionState,
    block: dict,
    stream_label: str,
    *,
    source: str,
) -> bool:
    """Run the policy gate on a tool_use block. Record trace events on rejection."""
    name = str(block.get("name") or "")
    raw_input = block.get("input") if isinstance(block.get("input"), dict) else {}
    evaluation = evaluate_tool_policy(runtime.action_policy, name, raw_input)
    if evaluation.decision is PolicyDecision.FORBIDDEN:
        if source == "text":
            state.record_tool_use_via_text(stream_label, block, status="blocked")
        state.record_trace_event(
            "tool_blocked",
            stage=stream_label,
            tool_name=name,
            reason=evaluation.reason,
            required_policy=evaluation.required_policy.value,
            current_policy=str(getattr(runtime.action_policy, "value", runtime.action_policy)),
        )
        return False
    if source == "text":
        state.record_tool_use_via_text(stream_label, block, status="planned")
    return True


