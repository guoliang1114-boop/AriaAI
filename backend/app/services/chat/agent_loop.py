def _build_assistant_message(text: str, tool_calls: list[dict], reasoning: str) -> dict:
    """Compose the assistant message dict to append to the LLM history."""
    content: list[dict] = []
    if text.strip():
        content.append({"type": "text", "text": text.strip()})
    for tc in tool_calls:
        content.append(
            {
                "type": "tool_use",
                "id": str(tc.get("id") or ""),
                "name": str(tc.get("name") or ""),
                "input": tc.get("input") or {},
            }
        )
    msg: dict[str, Any] = {"role": "assistant", "content": content}
    if reasoning:
        msg["reasoning_content"] = reasoning
    return msg


def _skipped_pending_result_block(tool_call: dict) -> dict:
    """Construct a synthetic tool_result for tool calls skipped after confirmation gate."""
    payload = {
        "ok": False,
        "success": False,
        "skipped": True,
        "status": "pending_confirmation",
        "reason": "前一个工具调用需要用户确认，本次未执行。",
    }
    return {
        "type": "tool_result",
        "tool_use_id": str(tool_call.get("id") or ""),
        "content": json.dumps(payload, ensure_ascii=False),
    }


def _append_text(existing: str, addition: str) -> str:
    if not addition:
        return existing
    if not existing:
        return addition
    return f"{existing.rstrip()}\n\n{addition}".strip()


def _checkpoint_step(state: ChatSessionState, step: AgentStep) -> None:
    if not state.rollout_task_id or state.rollout_bind is None:
        return
    try:
        checkpoint_chat_rollout(
            state.rollout_bind,
            state.rollout_task_id,
            step,
            state,
        )
    except Exception as exc:
        logger.warning("[rollout] failed to persist step checkpoint: %s", exc)
        state.record_trace_event(
            "rollout_checkpoint_failed",
            stage=f"step_{step.index}",
            error=str(exc)[:500],
        )


_PARALLEL_TOOL_STATE_LIST_FIELDS = (
    "pending_tool_confirmations",
    "pending_tool_actions",
    "trace_events",
    "artifacts",
    "pending_markdown_saves",
)


def _fork_parallel_tool_state(parent: ChatSessionState) -> ChatSessionState:
    """Create an isolated accumulator for one parallel-safe read call."""

    return ChatSessionState(
        run_id=parent.run_id,
        assistant_message_id=parent.assistant_message_id,
        stream_started_at=parent.stream_started_at,
    )


def _merge_parallel_tool_state(parent: ChatSessionState, child: ChatSessionState) -> None:
    """Merge one completed read call in original model-call order."""

    for event in child.tool_call_events:
        if isinstance(event, dict):
            parent.record_tool_execution(event)
    for field_name in _PARALLEL_TOOL_STATE_LIST_FIELDS:
        getattr(parent, field_name).extend(getattr(child, field_name))
    parent.confirmation_requested = parent.confirmation_requested or child.confirmation_requested
    parent.durable_task_completed = parent.durable_task_completed or child.durable_task_completed


